/* =========================================================
   5. PLACE ORDER (atomic)

   p_items: [{ "variant_id": 1, "quantity": 2 }, ...]
   Duplicated variant ids are merged. Variant rows are locked in
   id order so concurrent checkouts cannot deadlock or oversell.
   Re-sending the same p_request_id returns the original order.
========================================================= */

CREATE OR REPLACE FUNCTION public.store_place_order_atomic(
  p_user_id uuid,
  p_request_id uuid,
  p_reference text,
  p_items jsonb,
  p_recipient_name text,
  p_phone text,
  p_address_line text,
  p_subdistrict text,
  p_district text,
  p_province text,
  p_postal_code text,
  p_note text,
  p_slip_image_path text,
  p_shipping_fee_thb integer,
  p_free_shipping_min_thb integer
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_existing public.store_orders%ROWTYPE;
  v_order public.store_orders%ROWTYPE;
  v_line record;
  v_subtotal integer := 0;
  v_shipping integer;
  v_line_count integer;
BEGIN
  SELECT * INTO v_existing
  FROM public.store_orders
  WHERE request_id = p_request_id;

  IF FOUND THEN
    IF v_existing.user_id <> p_user_id THEN
      RAISE EXCEPTION 'LOOTFORM_SHOP_REQUEST_CONFLICT' USING ERRCODE = 'P0001';
    END IF;

    RETURN jsonb_build_object('order', to_jsonb(v_existing), 'replayed', true);
  END IF;

  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'LOOTFORM_SHOP_EMPTY_CART' USING ERRCODE = 'P0001';
  END IF;

  CREATE TEMP TABLE IF NOT EXISTS pg_temp.store_cart_lines (
    variant_id bigint PRIMARY KEY,
    quantity integer NOT NULL
  ) ON COMMIT DROP;

  TRUNCATE pg_temp.store_cart_lines;

  INSERT INTO pg_temp.store_cart_lines (variant_id, quantity)
  SELECT (item->>'variant_id')::bigint, SUM((item->>'quantity')::integer)
  FROM jsonb_array_elements(p_items) AS item
  GROUP BY (item->>'variant_id')::bigint;

  SELECT COUNT(*) INTO v_line_count FROM pg_temp.store_cart_lines;

  IF v_line_count > 20 THEN
    RAISE EXCEPTION 'LOOTFORM_SHOP_TOO_MANY_LINES' USING ERRCODE = 'P0001';
  END IF;

  IF EXISTS (
    SELECT 1 FROM pg_temp.store_cart_lines
    WHERE variant_id IS NULL OR quantity IS NULL OR quantity < 1 OR quantity > 10
  ) THEN
    RAISE EXCEPTION 'LOOTFORM_SHOP_INVALID_QUANTITY' USING ERRCODE = 'P0001';
  END IF;

  -- Lock every variant in a stable order before reading stock.
  PERFORM 1
  FROM public.store_product_variants v
  WHERE v.id IN (SELECT variant_id FROM pg_temp.store_cart_lines)
  ORDER BY v.id
  FOR UPDATE;

  IF (
    SELECT COUNT(*)
    FROM pg_temp.store_cart_lines c
    JOIN public.store_product_variants v ON v.id = c.variant_id
    JOIN public.store_products p ON p.id = v.product_id AND p.is_active
  ) <> v_line_count THEN
    RAISE EXCEPTION 'LOOTFORM_SHOP_PRODUCT_UNAVAILABLE' USING ERRCODE = 'P0001';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM pg_temp.store_cart_lines c
    JOIN public.store_product_variants v ON v.id = c.variant_id
    WHERE v.stock < c.quantity
  ) THEN
    RAISE EXCEPTION 'LOOTFORM_SHOP_OUT_OF_STOCK' USING ERRCODE = 'P0001';
  END IF;

  SELECT COALESCE(SUM(p.price_thb * c.quantity), 0)::integer
  INTO v_subtotal
  FROM pg_temp.store_cart_lines c
  JOIN public.store_product_variants v ON v.id = c.variant_id
  JOIN public.store_products p ON p.id = v.product_id;

  v_shipping := CASE
    WHEN v_subtotal >= p_free_shipping_min_thb THEN 0
    ELSE p_shipping_fee_thb
  END;

  INSERT INTO public.store_orders (
    reference, request_id, user_id, status,
    subtotal_thb, shipping_fee_thb, total_thb,
    recipient_name, phone, address_line, subdistrict, district,
    province, postal_code, note, payment_method, slip_image_path
  )
  VALUES (
    p_reference, p_request_id, p_user_id, 'PENDING',
    v_subtotal, v_shipping, v_subtotal + v_shipping,
    p_recipient_name, p_phone, p_address_line, p_subdistrict, p_district,
    p_province, p_postal_code, p_note, 'BANK_TRANSFER', p_slip_image_path
  )
  RETURNING * INTO v_order;

  FOR v_line IN
    SELECT
      c.variant_id, c.quantity, v.size,
      p.id AS product_id, p.name, p.slug, p.price_thb, p.images[1] AS image_url
    FROM pg_temp.store_cart_lines c
    JOIN public.store_product_variants v ON v.id = c.variant_id
    JOIN public.store_products p ON p.id = v.product_id
    ORDER BY c.variant_id
  LOOP
    UPDATE public.store_product_variants
    SET stock = stock - v_line.quantity, updated_at = now()
    WHERE id = v_line.variant_id;

    INSERT INTO public.store_order_items (
      order_id, product_id, variant_id, product_name, product_slug,
      size, image_url, unit_price_thb, quantity, line_total_thb
    )
    VALUES (
      v_order.id, v_line.product_id, v_line.variant_id, v_line.name, v_line.slug,
      v_line.size, v_line.image_url, v_line.price_thb, v_line.quantity,
      v_line.price_thb * v_line.quantity
    );
  END LOOP;

  RETURN jsonb_build_object('order', to_jsonb(v_order), 'replayed', false);
END;
$$;

REVOKE ALL ON FUNCTION public.store_place_order_atomic(
  uuid, uuid, text, jsonb, text, text, text, text, text, text, text, text, text, integer, integer
) FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.store_place_order_atomic(
