/* =========================================================
   6. ADMIN ORDER TRANSITIONS (atomic)

   APPROVE  PENDING  -> PAID
   REJECT   PENDING  -> CANCELLED (stock restored, reason required)
   SHIP     PAID     -> SHIPPED   (carrier + tracking required)
   DELIVER  SHIPPED  -> DELIVERED
   CANCEL   PAID     -> CANCELLED (stock restored, reason required)
========================================================= */

CREATE OR REPLACE FUNCTION public.store_order_transition_atomic(
  p_order_id bigint,
  p_admin_id uuid,
  p_action text,
  p_reason text,
  p_tracking_carrier text,
  p_tracking_number text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_order public.store_orders%ROWTYPE;
  v_expected text;
BEGIN
  v_expected := CASE p_action
    WHEN 'APPROVE' THEN 'PENDING'
    WHEN 'REJECT' THEN 'PENDING'
    WHEN 'SHIP' THEN 'PAID'
    WHEN 'DELIVER' THEN 'SHIPPED'
    WHEN 'CANCEL' THEN 'PAID'
    ELSE NULL
  END;

  IF v_expected IS NULL THEN
    RAISE EXCEPTION 'LOOTFORM_SHOP_INVALID_ACTION' USING ERRCODE = 'P0001';
  END IF;

  SELECT * INTO v_order
  FROM public.store_orders
  WHERE id = p_order_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'LOOTFORM_SHOP_ORDER_NOT_FOUND' USING ERRCODE = 'P0001';
  END IF;

  IF v_order.status <> v_expected THEN
    RAISE EXCEPTION 'LOOTFORM_SHOP_INVALID_STATUS' USING ERRCODE = 'P0001';
  END IF;

  IF p_action IN ('REJECT', 'CANCEL') AND COALESCE(BTRIM(p_reason), '') = '' THEN
    RAISE EXCEPTION 'LOOTFORM_SHOP_REASON_REQUIRED' USING ERRCODE = 'P0001';
  END IF;

  IF p_action = 'SHIP' AND (
    COALESCE(BTRIM(p_tracking_carrier), '') = '' OR COALESCE(BTRIM(p_tracking_number), '') = ''
  ) THEN
    RAISE EXCEPTION 'LOOTFORM_SHOP_TRACKING_REQUIRED' USING ERRCODE = 'P0001';
  END IF;

  IF p_action IN ('REJECT', 'CANCEL') THEN
    UPDATE public.store_product_variants v
    SET stock = v.stock + i.quantity, updated_at = now()
    FROM (
      SELECT variant_id, SUM(quantity)::integer AS quantity
      FROM public.store_order_items
      WHERE order_id = p_order_id AND variant_id IS NOT NULL
      GROUP BY variant_id
    ) i
    WHERE v.id = i.variant_id;
  END IF;

  UPDATE public.store_orders
  SET
    status = CASE p_action
      WHEN 'APPROVE' THEN 'PAID'
      WHEN 'SHIP' THEN 'SHIPPED'
      WHEN 'DELIVER' THEN 'DELIVERED'
      ELSE 'CANCELLED'
    END,
    reviewed_by = CASE WHEN p_action IN ('APPROVE', 'REJECT') THEN p_admin_id ELSE reviewed_by END,
    reviewed_at = CASE WHEN p_action IN ('APPROVE', 'REJECT') THEN now() ELSE reviewed_at END,
    paid_at = CASE WHEN p_action = 'APPROVE' THEN now() ELSE paid_at END,
    shipped_at = CASE WHEN p_action = 'SHIP' THEN now() ELSE shipped_at END,
    delivered_at = CASE WHEN p_action = 'DELIVER' THEN now() ELSE delivered_at END,
    tracking_carrier = CASE WHEN p_action = 'SHIP' THEN BTRIM(p_tracking_carrier) ELSE tracking_carrier END,
    tracking_number = CASE WHEN p_action = 'SHIP' THEN BTRIM(p_tracking_number) ELSE tracking_number END,
    cancel_reason = CASE WHEN p_action IN ('REJECT', 'CANCEL') THEN BTRIM(p_reason) ELSE cancel_reason END,
    updated_at = now()
  WHERE id = p_order_id
  RETURNING * INTO v_order;

  RETURN jsonb_build_object('order', to_jsonb(v_order));
END;
$$;

REVOKE ALL ON FUNCTION public.store_order_transition_atomic(bigint, uuid, text, text, text, text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.store_order_transition_atomic(bigint, uuid, text, text, text, text)
  TO service_role;

