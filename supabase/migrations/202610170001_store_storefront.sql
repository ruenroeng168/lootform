-- LOOTFORM Shop Storefront
-- Date: 2026-10-17
--
-- Purpose:
--   Direct-purchase apparel store (THB), separate from the LT craft
--   loop. Customer adds sized items to a cart, pays by bank transfer /
--   QR (the same bank details Admin configures in topup_settings),
--   uploads a slip, and an Admin reviews it.
--
--   Price, stock and totals are computed HERE, never trusted from the
--   client. Placing an order locks the variant rows, checks stock and
--   decrements it in one transaction; rejecting or cancelling an order
--   puts the stock back.
--
-- IMPORTANT:
--   Run this AFTER 202608252000_manual_topup_review.sql (payment details
--   come from topup_settings).
--   Deploy order: run this migration first, then deploy the app code.

BEGIN;

/* =========================================================
   1. PRODUCTS
========================================================= */

CREATE TABLE IF NOT EXISTS public.store_products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text NOT NULL CHECK (BTRIM(name) <> ''),
  category text NOT NULL
    CHECK (category IN ('TEES', 'HOODIES', 'OUTERWEAR', 'PANTS', 'ACCESSORIES')),
  description text NOT NULL DEFAULT '',
  price_thb integer NOT NULL CHECK (price_thb > 0),
  compare_at_price_thb integer CHECK (compare_at_price_thb IS NULL OR compare_at_price_thb > 0),
  images text[] NOT NULL DEFAULT '{}',
  color_name text,
  material text,
  fit text,
  care text,
  is_active boolean NOT NULL DEFAULT true,
  is_featured boolean NOT NULL DEFAULT false,
  is_new boolean NOT NULL DEFAULT false,
  sort_order int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS store_products_active_idx
  ON public.store_products (is_active, sort_order);

CREATE TABLE IF NOT EXISTS public.store_product_variants (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.store_products(id) ON DELETE CASCADE,
  size text NOT NULL CHECK (BTRIM(size) <> ''),
  stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT store_product_variants_unique_size UNIQUE (product_id, size)
);

