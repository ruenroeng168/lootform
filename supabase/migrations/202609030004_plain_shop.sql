-- LOOTFORM Plain Shop (direct buy, no Craft grade roll)
-- Date: 2026-09-03
--
-- Purpose:
--   A second, parallel purchase path alongside Craft: browse a plain
--   THB-priced catalog (shop_items), pick exactly what you get (no
--   server-side grade roll), pay via bank transfer + slip upload, an
--   Admin reviews and approves -- same manual-review trust model as
--   202608252000_manual_topup_review.sql, just for physical goods
--   instead of an LT top-up. Kept deliberately separate from
--   products/product_designs/items (those are wired to the season +
--   grade-roll system) so this never needs a fake "grade" value.
--
-- NOT YET APPLIED to the live project -- saved locally for review/testing.

BEGIN;

